fn push_position_accessor(
    accessors: &mut Vec<Value>,
    view: u32,
    stream: &VertexStream,
) -> Result<u32, GlbPackageError> {
    let (minimum, maximum) = position_bounds(&stream.positions)?;
    let index = checked_u32(accessors.len(), "position accessor index")?;
    accessors.push(json!({
        "bufferView": view,
        "componentType": FLOAT_COMPONENT,
        "count": checked_u32(stream.positions.len(), "position count")?,
        "type": "VEC3",
        "min": minimum,
        "max": maximum,
    }));
    Ok(index)
}

