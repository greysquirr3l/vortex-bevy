fn package_samplers(samplers: &[Sampler]) -> Result<Vec<Value>, GlbPackageError> {
    samplers
        .iter()
        .map(|sampler| {
            Ok(json!({
                "name": format!("Sampler{}", sampler.id.get()),
                "magFilter": gltf_mag_filter(sampler.mag_filter),
                "minFilter": sampler.min_filter.map(gltf_min_filter),
                "wrapS": gltf_wrap(sampler.wrap_s),
                "wrapT": gltf_wrap(sampler.wrap_t),
            }))
        })
        .collect()
}

fn package_textures(
    textures: &[Texture],
    sampler_indices: &BTreeMap<u32, u32>,
) -> Result<PackagedTextures, GlbPackageError> {
    let mut images = Vec::new();
    let mut values = Vec::new();
    for texture in textures {
        let image_index = checked_u32(images.len(), "GLB image index")?;
        images.push(json!({"name": format!("Image{}", texture.id.get()), "uri": texture.image}));
        let mut value = Map::new();
        value.insert("name".to_owned(), Value::from(format!("Texture{}", texture.id.get())));
        value.insert("source".to_owned(), Value::from(image_index));
        if let Some(sampler) = texture.sampler {
            value.insert(
                "sampler".to_owned(),
                Value::from(index_for(sampler.get(), sampler_indices, "sampler")?),
            );
        }
        values.push(Value::Object(value));
    }
    Ok(PackagedTextures { images, values })
}

fn package_materials(
    materials: &[Material],
    texture_indices: &BTreeMap<u32, u32>,
) -> Result<PackagedMaterials, GlbPackageError> {
    let mut values = Vec::new();
    let mut uses_texture_transform = false;
    for material in materials {
        if material.family != "pbr_metallic_roughness" {
            return Err(GlbPackageError::UnsupportedToken {
                kind: "material family",
                value: material.family.clone(),
            });
        }
        let base_color = texture_binding(
            material.textures.get("base_color").copied(),
            texture_indices,
            &material.texture_transform,
            &mut uses_texture_transform,
        )?;
        let metallic_roughness = texture_binding(
            material.textures.get("metallic_roughness").copied(),
            texture_indices,
            &material.texture_transform,
            &mut uses_texture_transform,
        )?;
        let normal = texture_binding(
            material.textures.get("normal").copied(),
            texture_indices,
            &material.texture_transform,
            &mut uses_texture_transform,
        )?;
        let occlusion = texture_binding(
            material.textures.get("occlusion").copied(),
            texture_indices,
            &material.texture_transform,
            &mut uses_texture_transform,
        )?;
        let emissive = texture_binding(
            material.textures.get("emissive").copied(),
            texture_indices,
            &material.texture_transform,
            &mut uses_texture_transform,
        )?;
        for slot in material.textures.keys() {
            if !matches!(
                slot.as_str(),
                "base_color" | "metallic_roughness" | "normal" | "occlusion" | "emissive"
            ) {
                return Err(GlbPackageError::UnsupportedToken {
                    kind: "material texture slot",
                    value: slot.clone(),
                });
            }
        }
        let mut pbr = Map::new();
        pbr.insert("baseColorFactor".to_owned(), json!(material.base_color));
        pbr.insert("metallicFactor".to_owned(), Value::from(material.metallic));
        pbr.insert("roughnessFactor".to_owned(), Value::from(material.roughness));
        if let Some(binding) = base_color {
            pbr.insert("baseColorTexture".to_owned(), binding);
        }
        if let Some(binding) = metallic_roughness {
            pbr.insert("metallicRoughnessTexture".to_owned(), binding);
        }
        let mut value = Map::new();
        value.insert("name".to_owned(), Value::from(format!("Material{}", material.id.get())));
        value.insert("pbrMetallicRoughness".to_owned(), Value::Object(pbr));
        value.insert("emissiveFactor".to_owned(), json!(material.emissive));
        value.insert("alphaMode".to_owned(), Value::from(gltf_alpha_mode(material.alpha_mode)));
        value.insert("doubleSided".to_owned(), Value::from(material.double_sided));
        if let Some(cutoff) = material.alpha_cutoff {
            value.insert("alphaCutoff".to_owned(), Value::from(cutoff));
        }
        if let Some(binding) = normal {
            let mut normal =
                binding.as_object().cloned().ok_or(GlbPackageError::DeferredFeature {
                    feature: "normal texture binding shape",
                })?;
            normal.insert("scale".to_owned(), Value::from(material.normal_scale));
            value.insert("normalTexture".to_owned(), Value::Object(normal));
        }
        if let Some(binding) = occlusion {
            let mut occlusion =
                binding.as_object().cloned().ok_or(GlbPackageError::DeferredFeature {
                    feature: "occlusion texture binding shape",
                })?;
            occlusion.insert("strength".to_owned(), Value::from(material.occlusion_strength));
            value.insert("occlusionTexture".to_owned(), Value::Object(occlusion));
        }
        if let Some(binding) = emissive {
            value.insert("emissiveTexture".to_owned(), binding);
        }
        values.push(Value::Object(value));
    }
    Ok(PackagedMaterials { values, uses_texture_transform })
}

fn texture_binding(
    texture: Option<crate::domain::scene_ir::TextureId>,
    texture_indices: &BTreeMap<u32, u32>,
    transform: &TextureTransform,
    uses_texture_transform: &mut bool,
) -> Result<Option<Value>, GlbPackageError> {
    let Some(texture) = texture else {
        return Ok(None);
    };
    let mut value = Map::new();
    value.insert(
        "index".to_owned(),
        Value::from(index_for(texture.get(), texture_indices, "texture")?),
    );
    if !identity_texture_transform(transform) {
        *uses_texture_transform = true;
        value.insert(
            "extensions".to_owned(),
            json!({"KHR_texture_transform": {"offset": transform.offset, "scale": transform.scale}}),
        );
    }
    Ok(Some(Value::Object(value)))
}

fn identity_texture_transform(transform: &TextureTransform) -> bool {
    transform.scale.iter().all(|value| value.to_bits() == 1.0_f32.to_bits())
        && transform.offset.iter().all(|value| value.to_bits() == 0.0_f32.to_bits())
}

const fn gltf_alpha_mode(mode: AlphaMode) -> &'static str {
    match mode {
        AlphaMode::Opaque => "OPAQUE",
        AlphaMode::Mask => "MASK",
        AlphaMode::Blend => "BLEND",
    }
}

const fn gltf_mag_filter(filter: TextureFilter) -> u32 {
    match filter {
        TextureFilter::Nearest => 9_728,
        TextureFilter::Linear => 9_729,
    }
}

const fn gltf_min_filter(filter: TextureFilter) -> u32 {
    gltf_mag_filter(filter)
}

const fn gltf_wrap(wrap: TextureWrap) -> u32 {
    match wrap {
        TextureWrap::Repeat => 10_497,
        TextureWrap::ClampToEdge => 33_071,
        TextureWrap::MirroredRepeat => 33_648,
    }
}

fn package_cameras(
    cameras: &[crate::domain::scene_ir::Camera],
) -> Result<Vec<Value>, GlbPackageError> {
    cameras
        .iter()
        .map(|camera| {
            if camera.projection != "perspective" {
                return Err(GlbPackageError::UnsupportedToken {
                    kind: "camera projection",
                    value: camera.projection.clone(),
                });
            }
            Ok(json!({
                "name": format!("Camera{}", camera.id.get()),
                "type": "perspective",
                "perspective": {"yfov": camera.primary_extent, "znear": 0.01},
            }))
        })
        .collect()
}

fn package_lights(lights: &[Light]) -> Result<Vec<Value>, GlbPackageError> {
    lights
        .iter()
        .map(|light| {
            if !matches!(light.kind.as_str(), "directional" | "point" | "spot") {
                return Err(GlbPackageError::UnsupportedToken {
                    kind: "light",
                    value: light.kind.clone(),
                });
            }
            Ok(json!({
                "name": format!("Light{}", light.id.get()),
                "type": light.kind,
                "intensity": light.intensity,
            }))
        })
        .collect()
}

fn package_skins(
    skins: &[Skin],
    joints: &[Joint],
    joint_indices: &BTreeMap<u32, u32>,
    node_indices: &BTreeMap<u32, u32>,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<Vec<Value>, GlbPackageError> {
    skins
        .iter()
        .map(|skin| {
            let joint_nodes = skin
                .joints
                .iter()
                .map(|joint_id| {
                    let joint_index = index_for(joint_id.get(), joint_indices, "joint")?;
                    let joint = joints
                        .get(usize::try_from(joint_index).map_err(|_| {
                            GlbPackageError::NumericOverflow { field: "joint index" }
                        })?)
                        .ok_or_else(|| GlbPackageError::MissingReference {
                            kind: "joint",
                            id: joint_id.get(),
                        })?;
                    index_for(joint.node.get(), node_indices, "joint node")
                })
                .collect::<Result<Vec<_>, GlbPackageError>>()?;
            let view = push_mat4_values(buffer, views, &skin.inverse_bind_matrices)?;
            let accessor = push_mat4_accessor(accessors, view, skin.inverse_bind_matrices.len())?;
            Ok(json!({
                "name": format!("Skin{}", skin.id.get()),
                "joints": joint_nodes,
                "inverseBindMatrices": accessor,
            }))
        })
        .collect()
}

fn mesh_skin_indices(
    meshes: &[Mesh],
    skin_indices: &BTreeMap<u32, u32>,
) -> Result<BTreeMap<u32, u32>, GlbPackageError> {
    meshes
        .iter()
        .filter_map(|mesh| mesh.skin.map(|skin| (mesh.id.get(), skin.get())))
        .map(|(mesh, skin)| Ok((mesh, index_for(skin, skin_indices, "skin")?)))
        .collect()
}

fn package_animations(
    clips: &[AnimationClip],
    channels: &[Channel],
    channel_indices: &BTreeMap<u32, u32>,
    node_indices: &BTreeMap<u32, u32>,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<Vec<Value>, GlbPackageError> {
    clips
        .iter()
        .map(|clip| {
            let mut samplers = Vec::new();
            let mut targets = Vec::new();
            for channel_id in &clip.channels {
                let channel_index =
                    index_for(channel_id.get(), channel_indices, "animation channel")?;
                let channel = channels
                    .get(usize::try_from(channel_index).map_err(|_| {
                        GlbPackageError::NumericOverflow { field: "animation channel index" }
                    })?)
                    .ok_or_else(|| GlbPackageError::MissingReference {
                        kind: "animation channel",
                        id: channel_id.get(),
                    })?;
                let input = push_animation_times(buffer, views, accessors, channel)?;
                let output = push_animation_values(buffer, views, accessors, channel)?;
                let sampler = checked_u32(samplers.len(), "animation sampler index")?;
                samplers.push(json!({"input": input, "output": output, "interpolation": "LINEAR"}));
                targets.push(json!({
                    "sampler": sampler,
                    "target": {
                        "node": index_for(channel.node.get(), node_indices, "animation node")?,
                        "path": channel.property,
                    },
                }));
            }
            Ok(json!({"name": clip.name, "samplers": samplers, "channels": targets}))
        })
        .collect()
}

fn push_animation_times(
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
    channel: &Channel,
) -> Result<u32, GlbPackageError> {
    let values = channel
        .keys
        .iter()
        .map(|key| seconds_to_f32(key.time_seconds))
        .collect::<Result<Vec<_>, _>>()?;
    let view = push_untyped_f32_values(buffer, views, &values)?;
    push_scalar_accessor(accessors, view, values.len(), "animation key count")
}

fn seconds_to_f32(seconds: f64) -> Result<f32, GlbPackageError> {
    if !seconds.is_finite() || seconds.abs() > f64::from(f32::MAX) {
        return Err(GlbPackageError::NumericOverflow { field: "animation key time" });
    }
    #[expect(
        clippy::cast_possible_truncation,
        reason = "The finite f64 time is explicitly bounded to the glTF f32 time domain."
    )]
    let narrowed = seconds as f32;
    Ok(narrowed)
}

fn push_animation_values(
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
    channel: &Channel,
) -> Result<u32, GlbPackageError> {
    let values = channel.keys.iter().flat_map(|key| key.value.iter().copied()).collect::<Vec<_>>();
    let view = push_untyped_f32_values(buffer, views, &values)?;
    let type_name = match channel.property.as_str() {
        "translation" | "scale" => "VEC3",
        "rotation" => "VEC4",
        "weights" => "SCALAR",
        _ => {
            return Err(GlbPackageError::UnsupportedToken {
                kind: "animation channel property",
                value: channel.property.clone(),
            });
        }
    };
    let count = if channel.property == "weights" { values.len() } else { channel.keys.len() };
    let index = checked_u32(accessors.len(), "animation value accessor index")?;
    accessors.push(json!({
        "bufferView": view,
        "componentType": FLOAT_COMPONENT,
        "count": checked_u32(count, "animation value count")?,
        "type": type_name,
    }));
    Ok(index)
}

fn package_nodes(
    nodes: &[Node],
    node_indices: &BTreeMap<u32, u32>,
    mesh_indices: &BTreeMap<u32, u32>,
    camera_indices: &BTreeMap<u32, u32>,
    light_indices: &BTreeMap<u32, u32>,
    mesh_skins: &BTreeMap<u32, u32>,
) -> Result<Vec<Value>, GlbPackageError> {
    nodes
        .iter()
        .map(|node| {
            package_node(
                node,
                nodes,
                node_indices,
                mesh_indices,
                camera_indices,
                light_indices,
                mesh_skins,
            )
        })
        .collect()
}

fn package_node(
    node: &Node,
    nodes: &[Node],
    node_indices: &BTreeMap<u32, u32>,
    mesh_indices: &BTreeMap<u32, u32>,
    camera_indices: &BTreeMap<u32, u32>,
    light_indices: &BTreeMap<u32, u32>,
    mesh_skins: &BTreeMap<u32, u32>,
) -> Result<Value, GlbPackageError> {
    let children = nodes
        .iter()
        .filter(|candidate| candidate.parent == Some(node.id))
        .map(|child| {
            node_indices.get(&child.id.get()).copied().ok_or_else(|| {
                GlbPackageError::MissingReference { kind: "child node", id: child.id.get() }
            })
        })
        .collect::<Result<Vec<_>, _>>()?;
    let mut value = Map::new();
    value.insert("name".to_owned(), Value::from(format!("Node{}", node.id.get())));
    value.insert("translation".to_owned(), json!(node.transform.translation));
    value.insert("rotation".to_owned(), json!(node.transform.rotation));
    value.insert("scale".to_owned(), json!(node.transform.scale));
    if !children.is_empty() {
        value.insert("children".to_owned(), json!(children));
    }
    if let Some(mesh) = node.mesh {
        value.insert("mesh".to_owned(), Value::from(index_for(mesh.get(), mesh_indices, "mesh")?));
    }
    if let Some(mesh) = node.mesh
        && let Some(skin) = mesh_skins.get(&mesh.get())
    {
        value.insert("skin".to_owned(), Value::from(*skin));
    }
    if let Some(camera) = node.camera {
        value.insert(
            "camera".to_owned(),
            Value::from(index_for(camera.get(), camera_indices, "camera")?),
        );
    }
    if let Some(light) = node.light {
        value.insert(
            "extensions".to_owned(),
            json!({"KHR_lights_punctual": {"light": index_for(light.get(), light_indices, "light")?}}),
        );
    }
    Ok(Value::Object(value))
}

fn root_nodes(
    nodes: &[Node],
    node_indices: &BTreeMap<u32, u32>,
) -> Result<Vec<u32>, GlbPackageError> {
    nodes
        .iter()
        .filter(|node| node.parent.is_none())
        .map(|node| index_for(node.id.get(), node_indices, "root node"))
        .collect()
}

fn index_for(
    id: u32,
    values: &BTreeMap<u32, u32>,
    kind: &'static str,
) -> Result<u32, GlbPackageError> {
    values.get(&id).copied().ok_or(GlbPackageError::MissingReference { kind, id })
}

fn labels(scene: &CanonicalScene) -> BTreeMap<String, u32> {
    let mut labels = BTreeMap::new();
    labels.insert("Scene0".to_owned(), 0);
    for node in &scene.nodes {
        labels.insert(format!("Node{}", node.id.get()), node.id.get());
    }
    for mesh in &scene.meshes {
        labels.insert(format!("Mesh{}", mesh.id.get()), mesh.id.get());
    }
    for material in &scene.materials {
        labels.insert(format!("Material{}", material.id.get()), material.id.get());
    }
    labels
}

#[derive(Default)]
struct BinaryBuffer {
    bytes: Vec<u8>,
}

impl BinaryBuffer {
    fn push_view(
        &mut self,
        views: &mut Vec<Value>,
        payload: Vec<u8>,
        target: u32,
    ) -> Result<u32, GlbPackageError> {
        align_bytes(&mut self.bytes, 0);
        let offset = checked_u32(self.bytes.len(), "buffer view offset")?;
        let length = checked_u32(payload.len(), "buffer view length")?;
        self.bytes.extend(payload);
        let view = checked_u32(views.len(), "buffer view index")?;
        views.push(
            json!({"buffer": 0, "byteOffset": offset, "byteLength": length, "target": target}),
        );
        Ok(view)
    }
}

fn encode_glb(document: &Value, mut binary: Vec<u8>) -> Result<Vec<u8>, GlbPackageError> {
    let mut json_bytes =
        serde_json::to_vec(document).map_err(|source| GlbPackageError::Json { source })?;
    align_bytes(&mut json_bytes, b' ');
    align_bytes(&mut binary, 0);
    let total = 12_usize
        .saturating_add(8)
        .saturating_add(json_bytes.len())
        .saturating_add(8)
        .saturating_add(binary.len());
    let total = checked_u32(total, "GLB total length")?;
    let json_length = checked_u32(json_bytes.len(), "GLB JSON chunk length")?;
    let binary_length = checked_u32(binary.len(), "GLB binary chunk length")?;
    let mut result = Vec::with_capacity(
        usize::try_from(total)
            .map_err(|_| GlbPackageError::NumericOverflow { field: "GLB capacity" })?,
    );
    push_u32(&mut result, GLB_MAGIC);
    push_u32(&mut result, GLB_VERSION);
    push_u32(&mut result, total);
    push_u32(&mut result, json_length);
    push_u32(&mut result, JSON_CHUNK_TYPE);
    result.extend(json_bytes);
    push_u32(&mut result, binary_length);
    push_u32(&mut result, BIN_CHUNK_TYPE);
    result.extend(binary);
    Ok(result)
}

fn align_bytes(bytes: &mut Vec<u8>, fill: u8) {
    while !bytes.len().is_multiple_of(4) {
        bytes.push(fill);
    }
}

fn push_u32(bytes: &mut Vec<u8>, value: u32) {
    bytes.extend_from_slice(&value.to_le_bytes());
}

fn checked_u32(value: usize, field: &'static str) -> Result<u32, GlbPackageError> {
    u32::try_from(value).map_err(|_| GlbPackageError::NumericOverflow { field })
}
