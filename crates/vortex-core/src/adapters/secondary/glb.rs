/// Deterministic GLB bytes, hash, and stable runtime labels.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GlbPackage {
    /// Complete GLB container bytes.
    pub bytes: Vec<u8>,
    /// SHA-256 checksum of `bytes`.
    pub checksum: ArtifactHash,
    /// Stable source-independent runtime lookup labels.
    pub labels: BTreeMap<String, u32>,
}

/// Failures emitted by the constrained Bevy-compatible GLB package adapter.
#[derive(Debug, Error)]
pub enum GlbPackageError {
    /// The public canonical scene fields failed revalidation before packaging.
    #[error("canonical scene is invalid for GLB packaging: {source}")]
    SceneInvalid { source: SceneIrError },
    /// A required IR object reference did not resolve during packaging.
    #[error("canonical scene has an unresolved {kind} reference during GLB packaging: {id}")]
    MissingReference { kind: &'static str, id: u32 },
    /// A numeric package offset/count did not fit glTF’s `u32` fields.
    #[error("GLB package value exceeds glTF u32 capacity: {field}")]
    NumericOverflow { field: &'static str },
    /// The canonical scene used a feature assigned to a later package layer.
    #[error("GLB package feature is not available in the constrained core subset: {feature}")]
    DeferredFeature { feature: &'static str },
    /// A camera or light kind cannot be expressed in the constrained subset.
    #[error("GLB package has an unsupported {kind} token: {value}")]
    UnsupportedToken { kind: &'static str, value: String },
    /// The generated bytes did not parse as glTF 2.0.
    #[error("generated GLB failed structural glTF parsing: {source}")]
    InvalidGlb { source: gltf::Error },
    /// Canonical JSON serialization failed while building the GLB JSON chunk.
    #[error("generated GLB JSON serialization failed: {source}")]
    Json { source: serde_json::Error },
}

/// Serializes canonical render data to a deterministic GLB core subset.
#[derive(Clone, Copy, Debug, Default)]
pub struct GlbWriter;

impl GlbWriter {
    /// Packages one validated canonical scene into a byte-stable GLB.
    ///
    /// # Errors
    ///
    /// Returns a typed error for unresolved IR references, non-core source features,
    /// texture staging requirements, unsupported camera/light tokens, overflowing GLB
    /// fields, JSON serialization failure, or structural glTF parsing failure.
    pub fn package(&self, scene: &CanonicalScene) -> Result<GlbPackage, GlbPackageError> {
        let scene = CanonicalScene::new(scene.clone())
            .map_err(|source| GlbPackageError::SceneInvalid { source })?;
        reject_deferred_features(&scene)?;
        let material_indices = index_by_id(scene.materials.iter().map(|value| value.id.get()))?;
        let stream_indices = index_by_id(scene.vertex_streams.iter().map(|value| value.id.get()))?;
        let primitive_indices = index_by_id(scene.primitives.iter().map(|value| value.id.get()))?;
        let mesh_indices = index_by_id(scene.meshes.iter().map(|value| value.id.get()))?;
        let node_indices = index_by_id(scene.nodes.iter().map(|value| value.id.get()))?;
        let camera_indices = index_by_id(scene.cameras.iter().map(|value| value.id.get()))?;
        let light_indices = index_by_id(scene.lights.iter().map(|value| value.id.get()))?;
        let texture_indices = index_by_id(scene.textures.iter().map(|value| value.id.get()))?;
        let sampler_indices = index_by_id(scene.samplers.iter().map(|value| value.id.get()))?;
        let joint_indices = index_by_id(scene.joints.iter().map(|value| value.id.get()))?;
        let skin_indices = index_by_id(scene.skins.iter().map(|value| value.id.get()))?;
        let channel_indices = index_by_id(scene.channels.iter().map(|value| value.id.get()))?;
        let morph_indices = index_by_id(scene.morph_targets.iter().map(|value| value.id.get()))?;

        let mut buffer = BinaryBuffer::default();
        let mut views = Vec::new();
        let mut accessors = Vec::new();
        let meshes = package_meshes(
            &scene.meshes,
            &scene.primitives,
            &scene.vertex_streams,
            &primitive_indices,
            &stream_indices,
            &material_indices,
            &scene.morph_targets,
            &morph_indices,
            &mut buffer,
            &mut views,
            &mut accessors,
        )?;
        let samplers = package_samplers(&scene.samplers)?;
        let textures = package_textures(&scene.textures, &sampler_indices)?;
        let materials = package_materials(&scene.materials, &texture_indices)?;
        let cameras = package_cameras(&scene.cameras)?;
        let lights = package_lights(&scene.lights)?;
        let skins = package_skins(
            &scene.skins,
            &scene.joints,
            &joint_indices,
            &node_indices,
            &mut buffer,
            &mut views,
            &mut accessors,
        )?;
        let mesh_skins = mesh_skin_indices(&scene.meshes, &skin_indices)?;
        let animations = package_animations(
            &scene.animation_clips,
            &scene.channels,
            &channel_indices,
            &node_indices,
            &mut buffer,
            &mut views,
            &mut accessors,
        )?;
        let nodes = package_nodes(
            &scene.nodes,
            &node_indices,
            &mesh_indices,
            &camera_indices,
            &light_indices,
            &mesh_skins,
        )?;
        let roots = root_nodes(&scene.nodes, &node_indices)?;
        let binary = buffer.bytes;
        let document = assemble_document(PackagedScene {
            roots,
            nodes,
            meshes,
            materials,
            samplers,
            textures,
            cameras,
            lights,
            skins,
            animations,
            views,
            accessors,
            binary_len: binary.len(),
        })?;
        let bytes = encode_glb(&document, binary)?;
        Gltf::from_slice(&bytes).map_err(|source| GlbPackageError::InvalidGlb { source })?;
        let labels = labels(&scene);
        Ok(GlbPackage { checksum: ArtifactHash::from_bytes(&bytes), bytes, labels })
    }
}

struct PackagedScene {
    roots: Vec<u32>,
    nodes: Vec<Value>,
    meshes: Vec<Value>,
    materials: PackagedMaterials,
    samplers: Vec<Value>,
    textures: PackagedTextures,
    cameras: Vec<Value>,
    lights: Vec<Value>,
    skins: Vec<Value>,
    animations: Vec<Value>,
    views: Vec<Value>,
    accessors: Vec<Value>,
    binary_len: usize,
}

fn assemble_document(parts: PackagedScene) -> Result<Value, GlbPackageError> {
    let mut document = Map::new();
    document.insert("asset".to_owned(), json!({"generator": "vortex-bevy", "version": "2.0"}));
    document.insert("scene".to_owned(), Value::from(0));
    document.insert("scenes".to_owned(), json!([{"name": "VortexScene", "nodes": parts.roots}]));
    document.insert("nodes".to_owned(), Value::Array(parts.nodes));
    document.insert("meshes".to_owned(), Value::Array(parts.meshes));
    document.insert("materials".to_owned(), Value::Array(parts.materials.values));
    document.insert("samplers".to_owned(), Value::Array(parts.samplers));
    document.insert("images".to_owned(), Value::Array(parts.textures.images));
    document.insert("textures".to_owned(), Value::Array(parts.textures.values));
    document.insert("bufferViews".to_owned(), Value::Array(parts.views));
    document.insert("accessors".to_owned(), Value::Array(parts.accessors));
    document.insert(
        "buffers".to_owned(),
        json!([{"byteLength": checked_u32(parts.binary_len, "buffer.byteLength")?}]),
    );
    if !parts.skins.is_empty() {
        document.insert("skins".to_owned(), Value::Array(parts.skins));
    }
    if !parts.animations.is_empty() {
        document.insert("animations".to_owned(), Value::Array(parts.animations));
    }
    if !parts.cameras.is_empty() {
        document.insert("cameras".to_owned(), Value::Array(parts.cameras));
    }
    let mut extensions = Vec::new();
    if parts.materials.uses_texture_transform {
        extensions.push("KHR_texture_transform");
    }
    if !parts.lights.is_empty() {
        extensions.push("KHR_lights_punctual");
        document.insert(
            "extensions".to_owned(),
            json!({"KHR_lights_punctual": {"lights": parts.lights}}),
        );
    }
    if !extensions.is_empty() {
        document.insert("extensionsUsed".to_owned(), json!(extensions));
    }
    Ok(Value::Object(document))
}

const fn reject_deferred_features(scene: &CanonicalScene) -> Result<(), GlbPackageError> {
    if !scene.instances.is_empty() {
        return Err(GlbPackageError::DeferredFeature { feature: "shared instances" });
    }
    Ok(())
}

fn index_by_id(ids: impl IntoIterator<Item = u32>) -> Result<BTreeMap<u32, u32>, GlbPackageError> {
    ids.into_iter()
        .enumerate()
        .map(|(index, id)| Ok((id, checked_u32(index, "GLB object index")?)))
        .collect()
}

struct PrimitiveContext<'a> {
    streams: &'a [VertexStream],
    stream_indices: &'a BTreeMap<u32, u32>,
    material_indices: &'a BTreeMap<u32, u32>,
    morph_targets: &'a [MorphTarget],
    morph_indices: &'a BTreeMap<u32, u32>,
}

#[expect(
    clippy::too_many_arguments,
    reason = "GLB package assembly owns all deterministic lookup tables and binary sections."
)]
fn package_meshes(
    meshes: &[Mesh],
    primitives: &[Primitive],
    streams: &[VertexStream],
    primitive_indices: &BTreeMap<u32, u32>,
    stream_indices: &BTreeMap<u32, u32>,
    material_indices: &BTreeMap<u32, u32>,
    morph_targets: &[MorphTarget],
    morph_indices: &BTreeMap<u32, u32>,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<Vec<Value>, GlbPackageError> {
    meshes
        .iter()
        .map(|mesh| {
            let mesh_primitives = mesh
                .primitives
                .iter()
                .map(|id| {
                    let index = primitive_indices.get(&id.get()).copied().ok_or_else(|| {
                        GlbPackageError::MissingReference { kind: "primitive", id: id.get() }
                    })?;
                    let primitive = primitives
                        .get(usize::try_from(index).map_err(|_| {
                            GlbPackageError::NumericOverflow { field: "primitive index" }
                        })?)
                        .ok_or_else(|| GlbPackageError::MissingReference {
                            kind: "primitive",
                            id: id.get(),
                        })?;
                    let context = PrimitiveContext {
                        streams,
                        stream_indices,
                        material_indices,
                        morph_targets,
                        morph_indices,
                    };
                    package_primitive(primitive, &context, buffer, views, accessors)
                })
                .collect::<Result<Vec<_>, GlbPackageError>>()?;
            Ok(json!({"name": format!("Mesh{}", mesh.id.get()), "primitives": mesh_primitives}))
        })
        .collect()
}

fn package_primitive(
    primitive: &Primitive,
    context: &PrimitiveContext<'_>,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<Value, GlbPackageError> {
    let stream_index =
        context.stream_indices.get(&primitive.vertex_stream.get()).copied().ok_or_else(|| {
            GlbPackageError::MissingReference {
                kind: "vertex stream",
                id: primitive.vertex_stream.get(),
            }
        })?;
    let stream = context
        .streams
        .get(
            usize::try_from(stream_index)
                .map_err(|_| GlbPackageError::NumericOverflow { field: "vertex stream index" })?,
        )
        .ok_or_else(|| GlbPackageError::MissingReference {
            kind: "vertex stream",
            id: primitive.vertex_stream.get(),
        })?;
    let attributes = package_attributes(stream, buffer, views, accessors)?;
    let index_view = push_indices(buffer, views, stream)?;
    let index_accessor = push_index_accessor(accessors, index_view, stream)?;
    let mut value = Map::new();
    value.insert("attributes".to_owned(), Value::Object(attributes));
    value.insert("indices".to_owned(), Value::from(index_accessor));
    value.insert("mode".to_owned(), Value::from(4));
    if let Some(material) = primitive.material {
        let index = context.material_indices.get(&material.get()).copied().ok_or_else(|| {
            GlbPackageError::MissingReference { kind: "material", id: material.get() }
        })?;
        value.insert("material".to_owned(), Value::from(index));
    }
    let targets = package_morph_targets(
        primitive,
        context.morph_targets,
        context.morph_indices,
        buffer,
        views,
        accessors,
    )?;
    if !targets.is_empty() {
        value.insert("targets".to_owned(), Value::Array(targets));
    }
    Ok(Value::Object(value))
}

fn package_attributes(
    stream: &VertexStream,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<Map<String, Value>, GlbPackageError> {
    let position_view = push_positions(buffer, views, stream)?;
    let position_accessor = push_position_accessor(accessors, position_view, stream)?;
    let mut attributes = Map::new();
    attributes.insert("POSITION".to_owned(), Value::from(position_accessor));
    if let Some(values) = &stream.normals {
        insert_float_attribute(
            &mut attributes,
            "NORMAL",
            values,
            "VEC3",
            buffer,
            views,
            accessors,
        )?;
    }
    if let Some(values) = &stream.tangents {
        insert_float_attribute(
            &mut attributes,
            "TANGENT",
            values,
            "VEC4",
            buffer,
            views,
            accessors,
        )?;
    }
    if let Some(values) = &stream.tex_coords_0 {
        insert_float_attribute(
            &mut attributes,
            "TEXCOORD_0",
            values,
            "VEC2",
            buffer,
            views,
            accessors,
        )?;
    }
    if let Some(values) = &stream.colors_0 {
        insert_float_attribute(
            &mut attributes,
            "COLOR_0",
            values,
            "VEC4",
            buffer,
            views,
            accessors,
        )?;
    }
    if let Some(values) = &stream.joints_0 {
        let view = push_u16_vec4_values(buffer, views, values)?;
        let accessor = push_attribute_accessor(
            accessors,
            view,
            values.len(),
            UNSIGNED_SHORT_COMPONENT,
            "VEC4",
        )?;
        attributes.insert("JOINTS_0".to_owned(), Value::from(accessor));
    }
    if let Some(values) = &stream.weights_0 {
        insert_float_attribute(
            &mut attributes,
            "WEIGHTS_0",
            values,
            "VEC4",
            buffer,
            views,
            accessors,
        )?;
    }
    Ok(attributes)
}

fn insert_float_attribute<const N: usize>(
    attributes: &mut Map<String, Value>,
    name: &'static str,
    values: &[[f32; N]],
    type_name: &'static str,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<(), GlbPackageError> {
    let view = push_float_vector_values(buffer, views, values)?;
    let accessor =
        push_attribute_accessor(accessors, view, values.len(), FLOAT_COMPONENT, type_name)?;
    attributes.insert(name.to_owned(), Value::from(accessor));
    Ok(())
}

fn package_morph_targets(
    primitive: &Primitive,
    morph_targets: &[MorphTarget],
    morph_indices: &BTreeMap<u32, u32>,
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    accessors: &mut Vec<Value>,
) -> Result<Vec<Value>, GlbPackageError> {
    primitive
        .morph_targets
        .iter()
        .map(|id| {
            let index = index_for(id.get(), morph_indices, "morph target")?;
            let target = morph_targets
                .get(usize::try_from(index).map_err(|_| GlbPackageError::NumericOverflow {
                    field: "morph target index",
                })?)
                .ok_or_else(|| GlbPackageError::MissingReference {
                    kind: "morph target",
                    id: id.get(),
                })?;
            let view = push_vec3_values(buffer, views, &target.position_deltas)?;
            let accessor = push_vec3_accessor(
                accessors,
                view,
                target.position_deltas.len(),
                "morph position count",
            )?;
            Ok(json!({"POSITION": accessor}))
        })
        .collect()
}

fn push_positions(
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    stream: &VertexStream,
) -> Result<u32, GlbPackageError> {
    let mut bytes = Vec::with_capacity(stream.positions.len().saturating_mul(12));
    for position in &stream.positions {
        for component in position {
            bytes.extend_from_slice(&component.to_le_bytes());
        }
    }
    buffer.push_view(views, bytes, ARRAY_BUFFER)
}

fn push_float_vector_values<const N: usize>(
    buffer: &mut BinaryBuffer,
    views: &mut Vec<Value>,
    values: &[[f32; N]],
) -> Result<u32, GlbPackageError> {
    let mut bytes = Vec::with_capacity(values.len().saturating_mul(N.saturating_mul(4)));
    for value in values {
        for component in value {
            bytes.extend_from_slice(&component.to_le_bytes());
        }
    }
    buffer.push_view(views, bytes, ARRAY_BUFFER)
}

