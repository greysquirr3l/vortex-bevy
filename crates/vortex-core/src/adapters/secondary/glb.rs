fn position_bounds(positions: &[[f32; 3]]) -> Result<([f32; 3], [f32; 3]), GlbPackageError> {
    let first = positions
        .first()
        .ok_or(GlbPackageError::DeferredFeature { feature: "empty position stream" })?;
    let mut minimum = *first;
    let mut maximum = *first;
    for position in positions {
        for ((minimum, maximum), value) in
            minimum.iter_mut().zip(maximum.iter_mut()).zip(position.iter())
        {
            if *value < *minimum {
                *minimum = *value;
            }
            if *value > *maximum {
                *maximum = *value;
            }
        }
    }
    Ok((minimum, maximum))
}

